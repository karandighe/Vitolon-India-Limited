  <script>
    function filterChemicals() {
      const query = document.getElementById('chemicalSearchInput').value.toLowerCase();
      const accordionItems = document.querySelectorAll('.chemical-accordion-item');

      accordionItems.forEach(item => {
        let hasMatch = false;
        const rows = item.querySelectorAll('tbody tr');

        rows.forEach(row => {
          const text = row.innerText.toLowerCase();
          if (text.includes(query)) {
            row.style.display = '';
            hasMatch = true;
          } else {
            row.style.display = 'none';
          }
        });

        const collapseEl = item.querySelector('.accordion-collapse');
        const buttonEl = item.querySelector('.accordion-button');

        if (query.length > 1 && hasMatch) {
          item.style.display = '';
          collapseEl.classList.add('show');
          buttonEl.classList.remove('collapsed');
          buttonEl.setAttribute('aria-expanded', 'true');
        } else if (query.length > 1 && !hasMatch) {
          item.style.display = 'none';
        } else {
          item.style.display = '';
          rows.forEach(r => r.style.display = '');
        }
      });
    }
